-- Картинка памятки обязательна. На сайте памятка — это карточка-изображение,
-- которая по клику открывается во весь экран, поэтому запись без image_path
-- давала бы битую картинку в обоих местах.
--
-- Правило уже закрыто в приложении (createReminder отдаёт 400 без файла, форма
-- админки требует изображение при создании, тип Reminder.image_path не nullable).
-- Здесь закрываем последний слой — схему, чтобы инвариант не зависел от кода.

-- 1) Старые записи (создавались, когда файл был необязателен) переводим на
-- заглушку. 'default.jpg' лежит в public/ фронта и раздаётся nginx из корня
-- сайта, поэтому `/${image_path}` отрисуется нормальным placeholder'ом, а не
-- битой картинкой. Значение сознательно отличается от обычных 'uploads/...':
-- это маркер «картинку надо догрузить в админке».
-- Если таких записей нет — UPDATE просто ничего не затронет.
UPDATE reminders SET image_path = 'default.jpg' WHERE image_path IS NULL;

-- 2) Теперь NULL невозможен. Миграция выполняется в транзакции (config/migrate.ts),
-- так что шаги 1 и 2 применяются вместе либо не применяются вовсе.
ALTER TABLE reminders ALTER COLUMN image_path SET NOT NULL;

import fsd from '@feature-sliced/steiger-plugin';
import { defineConfig } from 'steiger';

// Линтер архитектуры FSD. Держит то, ради чего слои и заведены: порядок импортов
// сверху вниз, отсутствие кросс-импортов внутри слоя, локальность.
//
// Четыре правила из recommended выключены осознанно — проект сознательно отступает
// от «полного» FSD, и без этих отключений линтер отдавал бы 28 ошибок из 29 на
// штатной структуре, то есть не ловил бы ничего.
export default defineConfig([
  ...fsd.configs.recommended,

  {
    ignores: ['**/*.test.ts', '**/*.test.tsx'],
  },

  {
    rules: {
      // ⚠️ Чего этот линтер здесь НЕ делает: не ловит импорты снизу вверх по слоям.
      // Проверено экспериментом — заведомое нарушение (entities/Event/EventCard.tsx
      // импортирует pages/home) не находится ни с recommended, ни при явном включении
      // fsd/no-higher-level-imports, fsd/no-cross-imports и fsd/import-locality.
      // Две очевидные причины проверены и НЕ подтвердились: не помогает ни добавление
      // публичного API слайсу (pages/home/index.ts + импорт через него), ни переход на
      // алиас (paths @/* в tsconfig + import из '@/pages/home/HomePage') — во всех
      // четырёх вариантах вывод «No problems found». Гранулярные правила при этом дают
      // 2 ошибки и 5 предупреждений на штатном коде, поэтому выключены: правило, которое
      // шумит и не ловит заявленного, хуже его отсутствия. Вывод для решений об
      // архитектуре: barrel-файлы и алиасы здесь машинной проверки слоёв НЕ дадут,
      // порядок слоёв держится ревью.

      // Слайсы плоские: компонент и его CSS-модуль лежат рядом
      // (pages/home/HomePage.tsx + HomePage.module.css), без разбиения на
      // ui/model/api. При таком размере слайса сегменты дали бы каталог на один
      // файл. Правило било бы во все 21 слайс проекта.
      'fsd/no-segmentless-slices': 'off',

      // Barrel-файлов (index.ts) в проекте нет нигде — импортируются конкретные
      // модули (78 глубоких импортов из одного только shared). Это осознанно:
      // barrel'ы ухудшают tree-shaking и HMR, а выигрыш на проекте такого размера
      // близок к нулю. Правила ходят парой: без публичного API нет и «обхода»
      // публичного API, поэтому выключаются вместе.
      'fsd/public-api': 'off',
      'fsd/no-public-api-sidestep': 'off',

      // shared/assets — картинки и логотипы. По букве FSD сегмент надо звать по
      // назначению, а не по содержимому, но `assets` — устоявшееся имя, и
      // переименование стоило бы правок импортов без выигрыша в понятности.
      'fsd/segments-by-purpose': 'off',
    },
  },

  {
    // Ложное срабатывание: слой entities импортируют почти все страницы, но
    // entities/types.ts лежит в корне слоя, а не внутри слайса, и линтер считает
    // сам слой слайсом без ссылок. Правило полезное (ловит мёртвый код), поэтому
    // глушится точечно, а не целиком.
    files: ['./src/entities/**'],
    rules: {
      'fsd/insignificant-slice': 'off',
    },
  },
]);
